#include <hardware/pio.h>
#include "RP2040_ppm.h"

ppmReader:: ppmReader() {
}
volatile uint32_t* ppmReader::begin(uint8_t rxPin)
{
  _rxPin = rxPin;
  // Neutral position (1500us) by default
  for (uint32_t i = 1; i < MAX_PPM_CHANNELS_RX; ++i) {
    _RX_Channels_values[i] = 1500;  // the array is MAX_PPM_CHANNELS_RX + 1 elements. 0 not used
  }
  _RX_Channels_values[0] = 0;  // fist element of the array gives the number of chanels in the frame.
  bool result = ppm_program_init_RX();

  if (!result) return NULL;
  _ppm_status = PPM_STOPPED;
  return _RX_Channels_values;
}

void ppmReader::start(void)
{
  _value_idx = 0;  // will force the wait of a sync pulse before reading the channels
  // 1. Get the interrupt source position for the specific state machine
  pio_interrupt_source_t source = pio_get_rx_fifo_not_empty_interrupt_source (_sm);
  uint irq_index = (_pio_irq - PIO0_IRQ_0) & 1;  // give 0 for PIO0_IRQ_0/PIO1_IRQ_0 and 1 for PIO0_IRQ_1/PIO1_IRQ_1
  pio_set_irqn_source_enabled (_pio, irq_index, source, true);
  pio_sm_clear_fifos(_pio, _sm); // FS
  // setup the IRQ handler
  if (_pio == pio0) {
    if (_pio_irq == PIO0_IRQ_0) {
      irq_set_exclusive_handler(PIO0_IRQ_0, isr_pio0_irq0);
      irq_set_enabled(PIO0_IRQ_0, true);
    } else {
      irq_set_exclusive_handler(PIO0_IRQ_1, isr_pio0_irq1);
      irq_set_enabled(PIO0_IRQ_1, true);
    }
  }
  else {  // pio1
    if (_pio_irq == PIO1_IRQ_0) {
      irq_set_exclusive_handler(PIO1_IRQ_0, isr_pio1_irq0);
      irq_set_enabled(PIO1_IRQ_0, true);
    } else {
      irq_set_exclusive_handler(PIO1_IRQ_1, isr_pio1_irq1);
      irq_set_enabled(PIO1_IRQ_1, true);
    }
  }
  pio_sm_set_enabled(_pio, _sm, true);  // lets go
  _newFrame = false;
  _ppm_status = PPP_STARTED;
}

void ppmReader::stop(void) {
  /*
    Disables the state machine (if running)
    Clears the FIFOs
    Applies the configuration specified by 'config'
    Resets any internal state e.g. shift counters
    Jumps to the initial program location given by 'initial_pc'
  */
  irq_set_enabled(_pio_irq, false);
  pio_sm_init (_pio, _sm, offset, &_pio_conf_rx);
  pio_sm_clear_fifos(_pio, _sm);
  pio_sm_set_clkdiv(_pio, _sm, (float) clock_get_hz(clk_sys) / PIO_CLOCK); //1MHz
  _newFrame = false;
  _ppm_status = PPM_STOPPED;
}

// end():  release the ressources : sm , irq handler,
void ppmReader::end() {
  ppmWriter::release_ressources(_pio, _sm, _pio_irq, ppm_rx_program, offset );
}

bool ppmReader::newFrame() {
  bool ii = _newFrame;
  _newFrame = false;
  return ii;
}
// called from begin()
bool ppmReader::ppm_program_init_RX() {
  // find a state machine in a pio with a free interrupt.
  bool reserved = ppmWriter::find_free_pio_sm_and_irq(&_pio, &_sm, &_pio_irq);
  if (!reserved) {
    return false;
  }
  else {
  }
  offset = pio_add_program(_pio, &ppm_rx_program);
  if (offset < 0) return false;
  uint pio_idx = pio_get_index(_pio); // Retourne 0 pour pio0, 1 pour pio1
  // 1. Enregistrer cette instance dans la table
  instances[pio_idx][_sm] = this;
  _pio_conf_rx = ppm_rx_program_get_default_config(offset);  // config as generated by pio asm.
  // Here we add our specific configuration.
  pio_sm_init(_pio, _sm, offset, &_pio_conf_rx);
  //  pio_sm_set_clkdiv(_pio, _sm, (float) clock_get_hz(clk_sys) / PIO_CLOCK); //1MHz
  // 200mhz RP2040 clock , 2mhz SM clock, 0.5us pio sm cycle
  pio_sm_set_clkdiv(_pio, _sm, 100);
  pio_sm_clear_fifos(_pio, _sm);
  pio_sm_set_jmp_pin (_pio, _sm, _rxPin) ;
  return true;
}
void ppmReader::dispatch_irq_rx(PIO pio, uint irq_index) {
  uint pio_idx = pio_get_index(pio);
  uint32_t status = (irq_index == 0) ? pio->ints0 : pio->ints1;
  // Vérifier chacune des 4 State Machines du bloc PIO
  for (uint sm = 0; sm < 4; sm++) {
    // Masque combinant les 3 causes possibles pour la SM 'sm' :
    // Bit 'sm' (RXNEMPTY) | Bit 'sm + 4' (TXNFULL) | Bit 'sm + 8' (Instruction IRQ)
    uint32_t sm_mask = (1u << sm) | (1u << (sm + 4)) | (1u << (sm + 8));
    if (status & sm_mask) {
      ppmReader* target = instances[pio_idx][sm];
      if (target != nullptr) {
        target->on_irq(); // Appel dans le contexte normal de l'objet !
      }
    }
  }
}

// Is called from the ISR dispacher, in the context of the object.
void ppmReader::on_irq() {
  while (!pio_sm_is_rx_fifo_empty (_pio, _sm)) {
    int pulse = pio_sm_get( _pio, _sm);
    if (pulse >= TX_MINIMUM_SPACE ) {
      // end of a frame. Save the nbr of channels in the frame, unlss it is the very first one.
      if ( _value_idx == 0 ) {
        _RX_Channels_values[0] =  0;
      } else {
        _RX_Channels_values[0] =  _value_idx - 1; // nbr of channel yet decoded for this frame
        _newFrame = true;
      }
      _value_idx = 1;  // reset to chanel 1
    }
    // at the very beginning we will wait un sync pulse. _value_idx is initialize to 0 in begin()
    else if (( _value_idx != 0) && (_value_idx <=  MAX_PPM_CHANNELS_RX )) {
      // the PIO asm program lost some cycle mesuring the H and L pulse:
      //  4 cycles for H + 2 cycles for low = 6  cycles, giving 3us at 2mhz sm clock
      _RX_Channels_values[ _value_idx] = pulse + 3;
      _value_idx++;
    }
  }
}
